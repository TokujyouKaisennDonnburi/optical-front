/**
 * メッセージからレスポンスタイプを判定する
 * @param message ユーザーメッセージ
 * @returns 適切なレスポンスタイプ
 */
export function getResponseTypeFromMessage(message: string): MockResponseType {
  for (const mapping of responseKeywordMapping) {
    if (mapping.keywords.some((keyword) => message.includes(keyword))) {
      return mapping.responseType;
    }
  }
  return "defaultResponse";
}

/**
 * メッセージから適切なモックレスポンスを取得する
 * @param message ユーザーメッセージ
 * @returns モックレスポンス文字列
 */
export function getMockResponseFromMessage(message: string): string {
  const responseType = getResponseTypeFromMessage(message);
  return mockAgentResponses[responseType];
}

